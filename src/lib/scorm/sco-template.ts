import type { ScormDesign } from "@/lib/scorm/types"

/**
 * Renders a self-contained SCORM 1.2 SCO from a learning design.
 *
 * Structure follows alfredang/workplacesafety-scorm: cover → narrated
 * video (gates progression) → topics with inline knowledge checks →
 * assessment intro → scored assessment → result. The run-time wrapper
 * (`scripts/scorm_api.js`) discovers `window.API` up the frame chain,
 * reports `cmi.core.lesson_status`, `cmi.core.score.*`,
 * `cmi.core.lesson_location` (bookmark), `cmi.suspend_data` (state) and
 * `cmi.core.session_time`, and degrades to "preview mode" without an LMS.
 *
 * All author/model text is HTML-escaped at render time; `bodyHtml` is
 * whitelisted to a handful of inline tags.
 */

export const SCORM_API_JS = `/*
 * SCORM 1.2 run-time wrapper — generated by Learnify SCORM Studio.
 * Discovers the LMS API (window.API) by walking the parent/opener chain
 * and degrades gracefully to preview mode when no LMS is present.
 */
var SCORM = (function () {
  var api = null;
  var initialised = false;
  var startedAt = null;

  function findAPI(win) {
    var tries = 0;
    try {
      while (win && !win.API && win.parent && win.parent !== win && tries < 500) {
        tries++;
        win = win.parent;
      }
      return win ? (win.API || null) : null;
    } catch (e) {
      return null;
    }
  }

  function getAPI() {
    var a = findAPI(window);
    if (!a) {
      try { if (window.opener) { a = findAPI(window.opener); } } catch (e) { a = null; }
    }
    return a;
  }

  function pad(n) { return (n < 10 ? "0" : "") + n; }

  function sessionTime() {
    if (!startedAt) { return "0000:00:00"; }
    var secs = Math.max(0, Math.round((new Date().getTime() - startedAt) / 1000));
    var h = Math.floor(secs / 3600), m = Math.floor((secs % 3600) / 60), s = secs % 60;
    return (h < 10 ? "000" : h < 100 ? "00" : h < 1000 ? "0" : "") + h + ":" + pad(m) + ":" + pad(s);
  }

  return {
    connected: function () { return !!api; },

    init: function () {
      api = getAPI();
      if (!api) { return false; }
      initialised = (String(api.LMSInitialize("")) === "true");
      if (initialised) {
        startedAt = new Date().getTime();
        var status = api.LMSGetValue("cmi.core.lesson_status");
        if (!status || status === "not attempted" || status === "") {
          api.LMSSetValue("cmi.core.lesson_status", "incomplete");
        }
        api.LMSCommit("");
      }
      return initialised;
    },

    set: function (key, value) {
      if (!initialised) { return false; }
      var ok = api.LMSSetValue(key, String(value));
      api.LMSCommit("");
      return String(ok) === "true";
    },

    get: function (key) {
      if (!initialised) { return ""; }
      return api.LMSGetValue(key);
    },

    setLocation: function (page) { return this.set("cmi.core.lesson_location", page); },

    setScore: function (raw, min, max) {
      this.set("cmi.core.score.min", min);
      this.set("cmi.core.score.max", max);
      return this.set("cmi.core.score.raw", raw);
    },

    setStatus: function (status) { return this.set("cmi.core.lesson_status", status); },

    setSuspendData: function (data) { return this.set("cmi.suspend_data", data); },

    finish: function () {
      if (!initialised) { return false; }
      this.set("cmi.core.session_time", sessionTime());
      this.set("cmi.core.exit", "suspend");
      var ok = api.LMSFinish("");
      initialised = false;
      return String(ok) === "true";
    }
  };
})();
`

const ALLOWED_TAGS = new Set(["h3", "p", "ul", "ol", "li", "b", "strong", "em", "i", "br"])

export function escapeHtml(s: string): string {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
}

/** Keep only a small whitelist of structural tags; strip attributes. */
export function sanitizeBodyHtml(html: string): string {
  if (!html) return ""
  return html
    .replace(/<\s*(script|style|iframe|object|embed|link|meta)[\s\S]*?<\/\s*\1\s*>/gi, "")
    .replace(/<\/?([A-Za-z0-9]+)[^>]*>/g, (full, tag: string) => {
      const t = tag.toLowerCase()
      if (!ALLOWED_TAGS.has(t)) return ""
      return full.startsWith("</") ? `</${t}>` : `<${t}>`
    })
    .replace(/javascript:/gi, "")
}

function jsString(value: unknown): string {
  // JSON is a safe JS literal once `</script>` sequences are neutralised.
  return JSON.stringify(value).replace(/<\/script/gi, "<\\/script").replace(/<!--/g, "<\\!--")
}

